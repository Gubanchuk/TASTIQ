// Rebuild the CC BY-SA TVmaze poster index from the local s01-tvmaze snapshot.
import { readFileSync, writeFileSync } from 'node:fs';
import { animeReleaseItem } from '../src/core/anime-release.js';
import { animePilot } from '../src/server/public/shared/anime-pilot.js';

const read = path => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const matchesById = new Map();
for (const show of read('../data/raw/tvmaze-shows.json')) {
  if (!show.imdb) continue;
  const matches = matchesById.get(show.imdb) ?? [];
  matches.push(show);
  matchesById.set(show.imdb, matches);
}

const anime = [
  ...Object.keys(animePilot).map(animeReleaseItem),
  ...read('../data/anime-wikidata.json').items,
];
const rows = [];
for (const { id, kind, year } of anime) {
  if (kind !== 'series') continue;
  const matches = matchesById.get(id);
  if (matches?.length !== 1) continue;
  const show = matches[0];
  if (Number(show.premiered?.slice(0, 4)) !== year || !Number.isSafeInteger(show.tvmaze) || show.tvmaze <= 0) continue;
  const path = /^https:\/\/static\.tvmaze\.com\/uploads\/images\/medium_portrait\/(\d+\/\d+\.(?:jpg|jpeg|png|webp))$/.exec(show.image)?.[1];
  if (path) rows.push([id, [show.tvmaze, path]]);
}

if (!rows.length) throw new Error('No exact anime poster matches in the TVmaze snapshot');
rows.sort(([a], [b]) => a.localeCompare(b));
const entries = rows.map(([id, value]) => `  ${JSON.stringify(id)}: ${JSON.stringify(value)},`);
const output = [
  '// TVmaze (CC BY-SA), https://www.tvmaze.com/api#licensing',
  '// Generated by scripts/import-anime-posters.mjs.',
  'export const tvmazeAnimePosters = {',
  ...entries,
  '};',
  '',
].join('\n');
writeFileSync(new URL('../src/server/public/data/anime-tvmaze-posters.js', import.meta.url), output);
console.log(`Matched ${rows.length} series posters by IMDb ID and premiere year.`);
