// Readable copy for both new responses and error strings in older saved selections.
const unavailable=/^(?:нейросеть (?:не подключена|выключена)|помощник недоступен|ключ OpenAI не принят|нет доступа к модели OpenAI|проверь баланс или лимит оплаты OpenAI)(?=\.|$)/i;
const interrupted=/^(?:нейросеть (?:перегружена|не закончила .+|не ответила(?: вовремя)?|отказалась отвечать|ответила не по форме.*|выбрала .+)|не удалось связаться с нейросетью|ошибка (?:обращения к нейросети|нейросети \d{3}))[.!]?$/i;
const budget=/^(?:доступный лимит нейросети исчерпан|новые обращения к нейросети временно остановлены|запрос не (?:запущен|отправлен): оставшийся бюджет недостаточен или цена модели неизвестна)(?=[.!?]|$)/i;

const unverifiedReading=/^(?:Неполный ответ помощника|Некорректн(?:ое понимание ответа|ый вывод о пожелании|ая форма вопроса)|Вывод не подтверждён (?:действующими ответами|точной цитатой действующего ответа)|Не удалось проверить (?:понимание ответа|источник вывода|основания вывода))[.!]?$/i;
const oversized=/^(?:запрос не запущен: контекст диалога отсутствует или превышает допустимый размер|Запрос не отправлен: раздел или контекст разговора некорректен либо превышает допустимый размер)[.!]?$/i;

export function aiErrorMessage(error){
 if(!error)return error;
 if(/^(?:Failed to fetch|NetworkError|Load failed|fetch failed|offline)(?:\b|$)/i.test(error))return 'Нет связи с сервером. Проверь подключение и попробуй ещё раз.';
 if(!/^[А-Яа-яЁё]/u.test(error))return 'Не удалось продолжить подбор. Попробуй ещё раз.';
 if(unavailable.test(error))return error.replace(unavailable,'Онлайн-подбор сейчас недоступен')
  .replace('Можно ответить на вопросы и посмотреть предварительные варианты.','Можно продолжить по вопросам и получить варианты из каталога.')
  .replace(/[^.!?]$/,'$&.');
 if(interrupted.test(error))return 'Не получилось продолжить подбор. Твои ответы сохранены.';
 if(budget.test(error))return 'Онлайн-подбор временно недоступен. Твои ответы сохранены.';
 if(unverifiedReading.test(error))return 'Не удалось проверить, правильно ли понят ответ. Можно повторить попытку.';
 if(oversized.test(error))return 'Не удалось обработать этот разговор. Начни новый подбор и укажи главные пожелания.';
 if(error==='Предыдущий запрос ещё не подтверждён. Повтор временно недоступен; ответы сохранены.')return 'Повтор пока недоступен. Твои ответы сохранены.';
 return error;
}

export function replacementNotice(notice){
 return notice?.replace('Он подобран по каталогу без нового обращения к модели.','Он подобран по каталогу.');
}
