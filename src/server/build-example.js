// Builds src/server/public/data/example-evenings.json for the landing: the game example walked through the real
// dialogue (reduce/screen, the same code the server runs) on the real catalog. The door posters are kept from the
// previous file. Run: node --max-old-space-size=8192 src/server/build-example.js
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadCatalogs } from '../core/catalog.js';
import { initialState, reduce, screen } from '../core/dialogue.js';
import { ROOT } from '../lib/fsx.js';

const FILE = resolve(ROOT, 'src', 'server', 'public', 'data', 'example-evenings.json');
const previous = JSON.parse(readFileSync(FILE, 'utf8'));
const catalogs = loadCatalogs();
const game = catalogs.game;
const label = (f) => game.dict.featureById.get(f)?.label ?? game.dict.complaintByFeature.get(f)?.label ?? f;
const complaint = (f) => game.dict.complaintByFeature.get(f)?.label ?? label(f);

// The example evening: a story fan who loves The Witcher 3, likes Stardew Valley, died too often in Dark Souls III
// and wants to unwind tonight.
const marks = [
  { id: 'steam:292030', reaction: 'love' }, // The Witcher 3
  { id: 'steam:413150', reaction: 'like' }, // Stardew Valley
  { id: 'steam:374320', reaction: 'dislike' }, // Dark Souls III
];
if (marks.some((m) => !game.byId.has(m.id))) throw new Error('an example title is missing from the catalog');
const reasons = { [marks[0].id]: ['story.central', 'characters.memorable'], [marks[1].id]: ['tone.cozy', 'loop.life_sim'] };
const prefer = ['tension.low', 'cognitive.low', 'tone.cozy'];

let state = initialState();
let scr = screen(state, catalogs);
const steps = [];
const send = (action, answer) => {
  steps.push({ step: scr.step, title: scr.title, answer });
  state = reduce(state, action, catalogs);
  scr = screen(state, catalogs);
};
send({ type: 'choose', value: 'game' }, 'game');
send({ type: 'choose', value: 'windows' }, 'ПК (Windows)');
send({ type: 'choose', value: 'solo' }, 'один');
send({ type: 'react', marks }, marks.map((m) => `${game.byId.get(m.id).ru ?? game.byId.get(m.id).name} (${{ love: 'обожаю', like: 'нормально', dislike: 'не моё' }[m.reaction]})`));
while (scr.step === 'why') {
  const id = scr.item.id;
  const values = (reasons[id] ?? []).filter((f) => scr.options.some((o) => o.value === f));
  send({ type: 'reasons', values }, { item: scr.item.ru ?? scr.item.name, reasons: values.map(label), love: state.answers[id]?.reaction === 'love' });
}
while (scr.step === 'why_not') send({ type: 'issues', issues: [{ f: 'difficulty.hard', hard: false }] }, { item: scr.item.ru ?? scr.item.name, complaints: [complaint('difficulty.hard')] });
if (scr.step === 'stops') send({ type: 'skip' }, []);
while (scr.step === 'ask') {
  const pick = scr.options.find((o) => prefer.includes(o.value));
  if (pick) send({ type: 'answer', qid: scr.qid, value: pick.value }, { question: scr.title, answer: pick.label });
  else send({ type: 'skip' }, { question: scr.title, answer: 'всё равно' });
}
if (scr.step !== 'result') throw new Error(`the walk stopped at ${scr.step}`);

const out = {
  note: `Real engine output for the landing, generated by src/server/build-example.js (reduce/screen on the real catalog) on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
  game: { domain: 'game', steps, result: scr.result },
  catalog: { domains: Object.fromEntries(Object.entries(catalogs).map(([id, c]) => [id, { items: c.items.length, dictionary: c.dict.version, label: c.domain.label }])) },
  posters: previous.posters,
};
writeFileSync(FILE, JSON.stringify(out, null, 1) + '\n', 'utf8');
console.log(`example: ${steps.map((s) => s.step).join(' → ')} → ${out.game.result.top.ru ?? out.game.result.top.name}`);
